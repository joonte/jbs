<?php
#-------------------------------------------------------------------------------
/** @author Alex Keda, for www.host-food.ru */
/******************************************************************************/
/******************************************************************************/
$__args_list = Array('Args');
/******************************************************************************/
Eval(COMP_INIT);
/******************************************************************************/
/******************************************************************************/
$Args = IsSet($Args)?$Args:Args();
#-------------------------------------------------------------------------------
$OrderID	= (integer) @$Args['OrderID'];
$Period		=  (string) @$Args['Period'];
#-------------------------------------------------------------------------------
if(Is_Error(System_Load('modules/Authorisation.mod')))
	return ERROR | @Trigger_Error(500);
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
// разбираем присланный период
switch($Period){
	case "w": $Period = Time() - 7*24*60*60;	break;	// week
	case "m": $Period = Time() - 30*24*60*60;	break;	// month
	case "a": $Period = 0;				break;	// all
	default:  $Period = Time() - 24*60*60;		break;	// day, default
}
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
// директория с файлами графиков
$Tmp = System_Element('tmp');
if(Is_Error($Tmp))
	return ERROR | @Trigger_Error(500);
#-------------------------------------------------------------------------------
$Path = SPrintF('%s/ResourceCharts/%u.json',$Tmp,$OrderID);
#-------------------------------------------------------------------------------
$Params = CacheManager::get($Path);
#-------------------------------------------------------------------------------
if(!$Params){
	#-------------------------------------------------------------------------------
	$Params = IO_Read($Path);
	if(Is_Error($Params))
		return Array();
	#-------------------------------------------------------------------------------
	CacheManager::add($Path,$Params,24*3600);
	#-------------------------------------------------------------------------------
}
#-------------------------------------------------------------------------------
$Params = Json_Decode($Params,TRUE);
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
// достаём владельца заказа
$Order = DB_Select('OrdersOwners',Array('ID','UserID','StatusID'),Array('ID'=>$OrderID,'UNIQ'));
switch(ValueOf($Order)){
case 'error':
	return ERROR | @Trigger_Error(500);
case 'exception':
	return Array();
case 'array':
	break;
default:
	return ERROR | @Trigger_Error(101);
}
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
// проверяем права юзера на этот заказ
$__USER = $GLOBALS['__USER'];
#-------------------------------------------------------------------------------
$IsPermission = Permission_Check('ServiceOrderRead',(integer)$__USER['ID'],(integer)$Order['UserID']);
#-------------------------------------------------------------------------------
switch(ValueOf($IsPermission)){
case 'error':
	return ERROR | @Trigger_Error(500);
case 'exception':
	return ERROR | @Trigger_Error(400);
case 'false':
	return ERROR | @Trigger_Error(700);
case 'true':
	break;
default:
	return ERROR | @Trigger_Error(101);
}
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
// меняем формат графиков на выходе
$Comp = Comp_Load('Formats/GraphOut',Array('Params'=>$Params,'StatusID'=>$Order['StatusID'],'Period'=>$Period));
if(Is_Error($Comp))
	return ERROR | @Trigger_Error(500);
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
return IsSet($Comp['Graphs'])?$Comp['Graphs']:Array();
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------

