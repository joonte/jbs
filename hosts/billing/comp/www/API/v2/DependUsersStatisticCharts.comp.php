<?php

#-------------------------------------------------------------------------------
/** @author Alex Keda, for www.host-food.ru */
/******************************************************************************/
/******************************************************************************/
$__args_list = Array('Args');
/******************************************************************************/
Eval(COMP_INIT);
/******************************************************************************/
/******************************************************************************/
$Args = IsSet($Args)?$Args:Args();
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
if(Is_Error(System_Load('modules/Authorisation.mod')))
        return ERROR | @Trigger_Error(500);
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
$Out = Array();
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
if(!IsSet($GLOBALS['__USER']))
	return $Out;
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
$Statistics = DB_Select('TmpData',Array('CreateDate','UpdateDate','Params'),Array('UNIQ','Where'=>Array('`UserID` = @local.__USER_ID','`AppID` = "DependUsers.Statistics"'),'Limits'=>Array(0,1)));
#-------------------------------------------------------------------------------
switch(ValueOf($Statistics)){
case 'error':
	return ERROR | @Trigger_Error(500);
case 'exception':
	return $Out;
case 'array':
	break;
default:
	return ERROR | @Trigger_Error(101);
}
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
/*
 * Name	
 * Units
 * Data
 * */
$Names = Array(
		'Summ'			=> 'Сумма вознаграждения',
		'ReferalsCount'		=> 'Число рефералов',
		'ReferalsWithPayments'	=> 'Рефералов с платежами',
		'ReferalsPaymentsCount'	=> 'Платежей рефералов',
		'ReferalsPaymentsSumm'	=> 'Сумма платежей рефералов',
		'ReferalsWorks'		=> 'Число работ',
		'ReferalsWithWorks'	=> 'Рефералов с выполненными работами',
		);

#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
foreach(Array_Keys($Statistics['Params']) as $Date){
	#-------------------------------------------------------------------------------
	foreach(Array_Keys($Statistics['Params'][$Date]) as $Key){
		#-------------------------------------------------------------------------------
		if(!IsSet($Out[$Key]['Data']))
			$Out[$Key]['Data'] = Array();
		#-------------------------------------------------------------------------------
		$Out[$Key]['Data'][] = Array(DoubleVal($Statistics['Params'][$Date][$Key]),$Date);
		#-------------------------------------------------------------------------------
		#-------------------------------------------------------------------------------
		// для заголовка
		$Out[$Key]['Name'] = $Names[$Key];
		#-------------------------------------------------------------------------------
		$Out[$Key]['Units']= Preg_Match('/Summ/',$Key)?'руб.':'шт.';
		#-------------------------------------------------------------------------------
	}
	#-------------------------------------------------------------------------------
}
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
return($Out);
#-------------------------------------------------------------------------------
